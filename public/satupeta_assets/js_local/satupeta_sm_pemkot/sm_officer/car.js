function play_vehicle() {
	if (Hls.isSupported()) {
		player_vehicle = videojs("my-video-vehicle");

		player_vehicle.ready(function () {
			var promise_vehicle = player_vehicle.autoplay("muted");

			if (promise_vehicle !== undefined) {
				promise_vehicle
					.then(function () {
						// Autoplay started!
						console.log("start");
					})
					.catch(function (error) {
						// Autoplay was prevented.
						console.log("error");
					});
			}
		});
		const config = {
			autoStartLoad: true,
			maxBufferSize: 1 * 1000 * 1000,
			manifestLoadingMaxRetry: 300000,
			manifestLoadingMaxRetryTimeout: 1000,
			levelLoadingMaxRetry: 300000,
			levelLoadingMaxRetryTimeout: 1000,
			fragLoadingMaxRetry: 300000,
			fragLoadingMaxRetryTimeout: 1000,
		};

		hls_vehicle = new Hls(config);

		retrying_vehicle = false;
		retry_vehicle = setInterval(
			() => retryLiveStreamVehicle(hls_vehicle, video_vehicle),
			1000
		);

		video_vehicle.onplaying = () => {
			isLoadingVehicle = false;
			hideErrorMsgVehicle = true;
			clearInterval(retry_vehicle);
			retrying_vehicle = false;
		};

		hls_vehicle.loadSource(url_st_vehicle);
		hls_vehicle.attachMedia(video_vehicle);
		hls_vehicle.on(Hls.Events.MANIFEST_PARSED, function () {
			video_vehicle.play();
		});

		hls_vehicle.on(Hls.Events.ERROR, function (event, data) {
			if (!hideErrorMsgVehicle) {
				isLoadingVehicle = true;
				hideErrorMsgVehicle = true;
			}
			if (data.fatal) {
				switch (data.type) {
					case Hls.ErrorTypes.NETWORK_ERROR:
						console.log("fatal network error encountered, try to recover");
						if (!retrying_vehicle) {
							retry_vehicle;
						}
						break;
					case Hls.ErrorTypes.MEDIA_ERROR:
						console.log("fatal media error encountered, try to recover");
						hls_vehicle.recoverMediaError();
						break;
				}
			}
		});
	}
}

function retryLiveStreamVehicle(hls_vehicle, video_vehicle) {
	retrying_vehicle = true;
	hls_vehicle.loadSource(document.getElementById("url_stream_vehicle").src);
	hls_vehicle.attachMedia(video_vehicle);
	hls_vehicle.startLoad();
}

