function konversiJamKeMenit(jam) {
    // Mengonversi jam ke menit
    var totalMenit = jam * 60;

    // Mengecek apakah total menit lebih dari 1440 (24 jam)
    if (totalMenit >= 1440) {
        var hari = Math.floor(totalMenit / 1440); // Mengambil bagian hari
        var sisaJam = totalMenit % 1440; // Mengambil sisa jam setelah dikonversi menjadi hari
        var jam = Math.floor(sisaJam / 60); // Mengambil bagian jam dari sisa jam
        var menit = sisaJam % 60; // Mengambil sisa menit dari sisa jam

        return hari + " D " +  jam + " H " +  Math.round(menit) + " M";
    } else if (totalMenit >= 60) { // Jika total menit lebih dari 60
        var jam = Math.floor(totalMenit / 60); // Mengambil bagian jam
        var sisaMenit = totalMenit % 60; // Mengambil sisa menit setelah dikonversi menjadi jam

        return jam + " H " +  Math.round(sisaMenit) + " M";
    } else { // Jika total menit kurang dari 60
        return  Math.round(totalMenit) + " M";
    }
}

