function getTitikPerjalanan(data = {}) {
	return new Promise(function (resolve, reject) {
		let key_dynamic = "";
		var arr_dump = []
		var requestCount = 0
		for (let i = 0; i < data.arrjourney.length; i++) {
			postDataSmNew(global_url_api + `sm_integration/titik_perjalanan`, {
				token: data.token,
				journeyId: data.arrjourney[i],
			}).then((v) => {
				key_dynamic = `${data.arrjourney[i]}`;
				ttk_poly_history[key_dynamic] = v.data;
				ttk_poly_history[key_dynamic].forEach((p) => {
					// polylineCoordinates[i].poly.push({ lat : parseFloat(p.latitude), lng : parseFloat(p.longitude)})
					p.angle = parseInt(p.angle);
					p.lat = parseFloat(p.latitude);
					p.lng = parseFloat(p.longitude);
					delete p.vehicleid;
					delete p.postime;
					// delete p.angle;
					delete p.speed;
					delete p.latitude;
					delete p.longitude;
					delete p.hdop;
				});
				polyline_history.push(
					new google.maps.Polyline({
						path: ttk_poly_history[key_dynamic],
						geodesic: true,
						// strokeColor: '#FF0000',
						strokeOpacity: 0.3,
						strokeWeight: 4,
						map: map,
					})
				);
				arr_dump.push(polyline_history)

				requestCount++;
                if (requestCount === data.arrjourney.length) {
                    ttk_poly_history.all = [].concat(...Object.values(ttk_poly_history));
                    map.setZoom(15);
                    map.setCenter(ttk_poly_history.all[0]);
                    resolve(ttk_poly_history);
                }
			}).catch((error) => {
                reject(error); // Reject if any request fails
            });
		}
	});
}

function clearPolyHistory() {
	clearInterval(animIntervalHistory);
	if (marker_s_e.length > 0) {
		for (let i = 0; i < marker_s_e.length; i++) {
			marker_s_e[i].setMap(null);
		}
		marker_s_e = [];
	}
	if (marker_car_history != undefined ) {
		marker_car_history.setMap(null);
		polylineFollowingMarkerHistory.setMap(null);
		marker_car_history = undefined;
		polylineFollowingMarkerHistory = "";
	}
	if (polyline_history.length > 0) {
		for (let i = 0; i < polyline_history.length; i++) {
			polyline_history[i].setMap(null);
		}
		polyline_history = [];
	}

	if (listJourneyidHistory.length > 0) {
		for (let i = 0; i < listJourneyidHistory.length; i++) {
			ttk_poly_history[listJourneyidHistory[i]] = [];
		}
		ttk_poly_history.all = [];
		listJourneyidHistory = [];
	}
}

