function mergePolylineCoordinates(polylineCoordinates) {
	var all = [];
	for (var i = 0; i < polylineCoordinates.length; i++) {
		all = all.concat(polylineCoordinates[i].poly);
	}
	return [{ poly: all }];
}
function createNumberedMarker(map, position, warna) {
	var marker = new google.maps.Marker({
		position: position,
		map: map,
		icon: {
			url: `https://maps.google.com/mapfiles/ms/icons/${warna}-dot.png`, // Icon marker (opsional)
			labelOrigin: new google.maps.Point(11, 50), // Posisi relatif label di dalam marker
		},
	});
	marker.addListener("click", function () {
		// Mendapatkan koordinat marker yang diklik
		var markerPosition = marker.getPosition();
		// Mengatur peta agar melakukan zoom ke marker yang diklik
		map.setZoom(20); // Misalnya, kita atur tingkat zoom ke 15
		map.setCenter(markerPosition); // Mengatur pusat peta pada posisi marker
	});
	return marker;
}
function stepAnimation(arr = []) {
	let polypoly = arr;
	animIntervalHistory = setInterval(stepAnimations, delayHistory);
	function stepAnimations() {
		if (stepHistory >= numStepsHistory * (polypoly.length - 1)) {
			clearInterval(animIntervalHistory);
			return;
		}
		stepHistory++;
		var index = Math.floor(stepHistory / numStepsHistory);
		var fraction = (stepHistory % numStepsHistory) / numStepsHistory;
		var icon = marker_car_history.getIcon();
		if (index < polypoly.length - 1) {
			var position = google.maps.geometry.spherical.interpolate(
				polypoly[index],
				polypoly[index + 1],
				fraction
			);
			marker_car_history.setPosition(position);
			updateFollowingPolyline(position);
			icon.rotation = polypoly[index].angle;
			marker_car_history.setIcon(icon);
		}
	}
}

function updateFollowingPolyline(position) {
	var pathFollowing = polylineFollowingMarkerHistory.getPath();
	pathFollowing.push(position);
	polylineFollowingMarkerHistory.setPath(pathFollowing);
}

